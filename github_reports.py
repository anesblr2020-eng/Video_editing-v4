"""Optional, explicit publishing of small scene-plan reports to a public GitHub repo."""
from __future__ import annotations

import base64
import os
import re
from datetime import datetime, timezone
from typing import Any
from urllib.parse import quote

import requests


def _setting(name: str, default: str = "") -> str:
    value = os.getenv(name, "")
    if value:
        return value
    try:
        import streamlit as st
        value = st.secrets.get(name, "")
        if value:
            return str(value)
    except Exception:
        pass
    return default


def github_report_settings() -> dict[str, str]:
    return {
        "token": _setting("GITHUB_TOKEN"),
        "owner": _setting("GITHUB_REPO_OWNER", "anesblr2020-eng"),
        "repo": _setting("GITHUB_REPO_NAME", "Video_editing-v4"),
        "branch": _setting("GITHUB_REPO_BRANCH", "main"),
    }


def publish_scene_plan(plan: list[dict[str, Any]], source_text: str = "") -> dict[str, str]:
    """Publish only when explicitly called by the user. Repo is public, so content is public."""
    cfg = github_report_settings()
    if not cfg["token"]:
        raise RuntimeError("لم يُضف GITHUB_TOKEN بعد إلى Secrets في منصة الاستضافة.")
    if not cfg["owner"] or not cfg["repo"] or not cfg["branch"]:
        raise RuntimeError("إعدادات مستودع GitHub غير مكتملة.")

    now = datetime.now(timezone.utc)
    stamp = now.strftime("%Y%m%d-%H%M%S-UTC")
    safe_path = f"reports/scene-plan-{stamp}.json"
    payload = {
        "report_type": "semantic_scene_plan",
        "created_at_utc": now.isoformat(),
        "repository": f"{cfg['owner']}/{cfg['repo']}",
        "planner": "local_heuristic_v1",
        "scene_count": len(plan),
        "scenes": plan,
        "notes": [
            "Generated by the local heuristic planner; not a claim of deep semantic understanding.",
            "This report is public because the target GitHub repository is public.",
        ],
    }
    import json
    content = json.dumps(payload, ensure_ascii=False, indent=2).encode("utf-8")
    api_url = f"https://api.github.com/repos/{quote(cfg['owner'], safe='')}/{quote(cfg['repo'], safe='')}/contents/{safe_path}"
    headers = {
        "Authorization": f"Bearer {cfg['token']}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    body = {
        "message": f"Add scene plan report {stamp}",
        "content": base64.b64encode(content).decode("ascii"),
        "branch": cfg["branch"],
    }
    response = requests.put(api_url, headers=headers, json=body, timeout=25)
    if response.status_code not in (200, 201):
        detail = ""
        try:
            detail = str(response.json().get("message", ""))
        except Exception:
            pass
        if response.status_code in (401, 403):
            raise RuntimeError(f"رفض GitHub النشر. تحقق من صلاحية Contents: Read and write للرمز والفرع. {detail}")
        if response.status_code == 404:
            raise RuntimeError(f"لم يعثر GitHub على المستودع أو الفرع. تحقق من الاسم والفرع. {detail}")
        raise RuntimeError(f"فشل النشر إلى GitHub (HTTP {response.status_code}). {detail}")

    page_url = f"https://github.com/{cfg['owner']}/{cfg['repo']}/blob/{quote(cfg['branch'], safe='')}/{safe_path}"
    raw_url = f"https://raw.githubusercontent.com/{cfg['owner']}/{cfg['repo']}/{quote(cfg['branch'], safe='')}/{safe_path}"
    return {"path": safe_path, "url": page_url, "raw_url": raw_url, "created_at": now.isoformat()}
